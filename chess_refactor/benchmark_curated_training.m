function report = benchmark_curated_training()
%BENCHMARK_CURATED_TRAINING Measure one short GPU workload before long runs.
settings = struct( ...
    "iterations", 1, ...
    "selfPlayGamesPerIteration", 9, ...
    "mctsSimulations", 4, ...
    "maxPlies", 20, ...
    "trainingStepsPerIteration", 1, ...
    "batchSize", 8, ...
    "evaluationGamesPerPosition", 1, ...
    "modelDirectory", "models/benchmark", ...
    "replayDirectory", "replay/benchmark");
started = tic;
history = train_endgame_alphazero(settings);
elapsedSeconds = toc(started);
selfPlay = history.selfPlay;
totalPlies = sum([selfPlay.games] .* [selfPlay.averagePlies]);
report = struct("elapsedSeconds", elapsedSeconds, "totalSelfPlayPlies", totalPlies, ...
    "selfPlayPliesPerSecond", totalPlies / elapsedSeconds, "history", history);
end
