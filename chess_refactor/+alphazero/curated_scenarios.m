function scenario = make_scenario(id, name, player, challengePlayer, expectedResult, source, pieces)
board = zeros(10, 9);
for index = 1:size(pieces, 1)
    piece = pieces(index, 1);
    col = pieces(index, 2);
    row = pieces(index, 3);
    if board(row, col) ~= 0
        error("alphazero:DuplicateScenarioSquare", "Scenario %s has duplicate squares.", id);
    end
    board(row, col) = piece;
end
scenario = empty_scenario();
scenario.id = id;
scenario.name = name;
scenario.board = board;
scenario.player = player;
scenario.challengePlayer = challengePlayer;
scenario.expectedResult = expectedResult;
scenario.maxPlies = 120;
scenario.source = source;
end

function scenario = empty_scenario()
scenario = struct("id", "", "name", "", "board", zeros(10, 9), ...
    "player", 1, "challengePlayer", 1, "expectedResult", "", ...
    "maxPlies", 120, "source", struct());
end
